import 'dart:io';

// The shader asset is canonical. Outputs are checked-in build inputs, so a
// consumer needs no sibling repository or generator at compilation time.
void main(List<String> arguments) {
  var check = false;
  String? nativePath, rustPath;
  for (var i = 0; i < arguments.length; i++) {
    final argument = arguments[i];
    if (argument == '--check') {
      check = true;
    } else if ((argument == '--native-output' || argument == '--rust-output') &&
        i + 1 < arguments.length) {
      if (argument == '--native-output') {
        nativePath = arguments[++i];
      } else {
        rustPath = arguments[++i];
      }
    } else {
      stderr.writeln(
        'Usage: dart generate_capture_recipe.dart [--check] '
        '[--native-output PATH] [--rust-output PATH]',
      );
      exitCode = 64;
      return;
    }
  }
  final root = File.fromUri(Platform.script).parent.parent;
  final shader = File(
    '${root.path}/src/shaders/capture_rgba_v1.wgsl',
  ).readAsStringSync();
  if (shader.contains('\r') ||
      !shader.endsWith('\n') ||
      shader.contains(')MGPU_CAPTURE1"') ||
      shader.contains('"##')) {
    throw FormatException(
      'Canonical shader must be LF text with safe delimiters',
    );
  }
  const generated =
      '// Generated by tool/generate_capture_recipe.dart. '
      'Edit the canonical WGSL/tool, not this file.\n';
  final native =
      '''$generated#ifndef MINIGPU_CAPTURE_RECIPE_V1_H
#define MINIGPU_CAPTURE_RECIPE_V1_H
#include <cstdint>
#include <string_view>
namespace mgpu::capture_recipe_v1 {
inline constexpr uint32_t revision = 1;
inline constexpr uint32_t packedUsage = 0x84;
inline constexpr uint32_t parametersUsage = 0x48;
inline constexpr uint32_t parameterBytes = 16;
inline constexpr uint32_t frameSlot = 0, packedSlot = 1, parametersSlot = 2;
inline constexpr uint32_t workgroupSide = 8;
inline constexpr std::string_view wgsl = R"MGPU_CAPTURE1($shader)MGPU_CAPTURE1";
} // namespace mgpu::capture_recipe_v1
#endif
''';
  final rust =
      '''${generated}const PACKED_USAGE: u32 = 0x84;
const PARAMETERS_USAGE: u32 = 0x48;
const PARAMETER_BYTES: u64 = 16;
const FRAME_SLOT: u32 = 0;
const PACKED_SLOT: u32 = 1;
const PARAMETERS_SLOT: u32 = 2;
const WORKGROUP_SIDE: u32 = 8;
const WGSL: &str = r##"$shader"##;
''';
  final outputs = <File, String>{
    File(nativePath ?? '${root.path}/src/include/minigpu_capture_recipe_v1.h'):
        native,
    if (rustPath != null) File(rustPath): rust,
  };
  for (final entry in outputs.entries) {
    if (check) {
      if (!entry.key.existsSync() ||
          entry.key.readAsStringSync() != entry.value) {
        stderr.writeln('Out of date: ${entry.key.path}');
        exitCode = 1;
      }
    } else {
      entry.key.parent.createSync(recursive: true);
      entry.key.writeAsStringSync(entry.value);
    }
  }
  if (exitCode == 0) {
    stdout.writeln(
      '${check ? 'PASS' : 'Generated'} ${outputs.length} recipe outputs',
    );
  }
}
